const dict: Record<Lang, Record<I18nKey, string>> = { zh, en };
let lang: Lang = 'zh';
export function setLang(l: Lang) { lang = l; }
export function getLang(): Lang { return lang; }
export function t(key: I18nKey, params?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? zh[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
/** 全部文案(守卫测试用) */
export function allStrings(): string[] {
  return [...Object.values(dict.zh), ...Object.values(dict.en)];
}
